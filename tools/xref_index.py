"""Build _data/xref.yml, the shared index of cross-book link targets, from the five built sites.

    python3 tools/xref_index.py <built-sites-dir> > xref.yml

<built-sites-dir> holds each book's built Jekyll site under its URL name (arch-book/, ...).
Keys: "<book>" (the book), "<book>:<n>" (chapter n), "<book>:<n.m>" (section n.m),
"<book>:f<n.m>" (figure n.m, which opens its chapter), "<book>:a" (the appendix).
Anchors come from the built pages, so every link points at an id that exists.
"""
import html
import os
import re
import sys

BOOKS = [  # key, URL name, short title, full title
    ("architecture", "arch-book", "Software Architecture", "Software Architecture in the AI & Cloud Era"),
    ("products", "buildproducts-book", "Building Products", "Building Products in the AI & Cloud Era"),
    ("software", "buildsoftware-book", "Building Software at Scale", "Building Software at Scale in the AI & Cloud Era"),
    ("resilience", "resilienteng-book", "Building Resilient Systems", "Building Resilient Systems in the AI & Cloud Era"),
    ("operations", "prodsys-book", "Operating Production Systems", "Operating Production Systems in the AI & Cloud Era"),
]
BASE = "https://oleksiyp.github.io"


def text(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


root = sys.argv[1]
out = ["# Cross-book link targets, generated by softwarebook-series/tools/xref_index.py. Identical in every book."]
for i, (key, site, short, full) in enumerate(BOOKS, 1):
    d = os.path.join(root, site)
    out.append(f"{q(key)}: {{book: {key}, url: {q(f'{BASE}/{site}/')}, label: {q(f'{full} · Book {i}')}}}")
    n = 1
    while os.path.exists(os.path.join(d, "ch", str(n), "index.html")):
        page = open(os.path.join(d, "ch", str(n), "index.html")).read()
        url = f"{BASE}/{site}/ch/{n}/"
        h2 = re.search(rf'<h2[^>]*id="ch{n}"[^>]*>(.*?)</h2>', page, re.S)
        if not h2:  # a redirect left at an old chapter URL, not a chapter
            break
        ctitle = re.sub(r"^Chapter \d+:\s*", "", text(h2.group(1)))
        out.append(f"{q(f'{key}:{n}')}: {{book: {key}, url: {q(url)}, label: {q(f'{short} · Chapter {n} · {ctitle}')}}}")
        out.append(f"{q(f'{key}:f{n}')}: {{book: {key}, url: {q(url)}, label: {q(f'{short} · Chapter {n} · {ctitle}')}}}")
        for m in re.finditer(r'<h3[^>]*\sid="([^"]+)"[^>]*>(.*?)</h3>', page, re.S):
            t = text(m.group(2))
            sm = re.match(r"(\d+)\.(\d+)\s+(.*)", t)
            if sm and int(sm.group(1)) == n:
                sec = f"{n}.{sm.group(2)}"
                out.append(f"{q(f'{key}:{sec}')}: {{book: {key}, url: {q(url + '#' + m.group(1))}, label: {q(f'{short} · Section {sec} · {sm.group(3)}')}}}")
        n += 1
    if os.path.exists(os.path.join(d, "appendix", "encore", "index.html")):
        out.append(f"{q(f'{key}:a')}: {{book: {key}, url: {q(f'{BASE}/{site}/appendix/encore/')}, label: {q(f'{short} · Appendix · Encore at a Glance')}}}")
print("\n".join(out))
